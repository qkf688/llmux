package common

import "net/http"

// IsPassingStatus 判定上游响应状态码是否算「这次请求成功」——全项目唯一口径：
// **仅 200 与 201**。
//
// 为什么带 201：OpenAI 兼容网关中有相当一部分照抄 OpenAI 某些接口的习惯回 201，它们
// 工作正常、内容有效。旧的严格 `== 200` 把这类供应商判为失败，代价不止诊断报错——
// 健康检查的失败累计会自动停用模型-供应商关联，线上白白少一条可用线路，且停用原因
// 不入库，事后只能从错误文本反推（Stage 5，2026-09-17 共识：统一到认 201）。
//
// 为什么**不**放宽到整个 2xx：放宽的全部理由只有「有些网关回 201」。204/206 这类
// 「成功但没有正文」的状态码从来不是聊天补全该有的回答——若一并判通过，直通链路（请求
// 形状与上游一致、不进转换层，因此没有任何解析步骤会失败）会把它当成功：空 body 直接
// 回给调用方，同时走成功副作用（权重/优先级上调、失败计数清零、健康检查 autoEnable
// 重新启用关联）。那等于给坏供应商加权，比误停用更难发现。保持失败语义 = 沿用 Stage 5
// 之前的处置（记 error + 组织级衰减 + 换下一家），不新增行为。
//
// 为什么落在 common 而不是由 service/credprobe 导出：本判定被 7 处共用，其中两处在
// providers 层（拉模型列表），按依赖方向 providers 禁止 import service 子包；跨 2 个
// 以上域的纯逻辑必须下沉 common（AGENTS §4.4）。
//
// 边界：本函数**只管状态码**，不判响应内容。上游回 200/201 但内容并非一份合法回复
// （被重定向到登录页、回一页 HTML 错误页那类）不在此拦截——各调用点对内容有效性的
// 要求本就不同（聊天要能解析成回复、模型列表要能解析成清单、流式测试要看到真在吐字），
// 捆进同一个判定会让改聊天校验连带牵动模型列表（Stage 5 共识第 4 条，已记为残留待办）。
//
// 配套执法：非测试代码禁止再对上游状态码做裸比较判通过/失败，见 gate_upstream_status_test.go。
func IsPassingStatus(statusCode int) bool {
	return statusCode == http.StatusOK || statusCode == http.StatusCreated //gate:upstream-status-allow 通过口径的定义本体，全项目唯一允许直接比状态码的地方
}
